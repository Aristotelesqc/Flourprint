import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';

export const REPOSITORY = 'Aristotelesqc/Flourprint';
export const VIEW_MARKER = '<!-- flourprint-backlog-view:v1 -->';
const TARGET = 30;
const PAGE_SIZE = 100;
const groups = {
  status: ['blocked', 'review', 'in-progress', 'ready', 'verified', 'backlog'],
  area: ['engine', 'science', 'data', 'ui', 'platform', 'docs', 'governance'],
  milestone: ['alpha', 'engine-mvp', 'later'],
  priority: ['p0', 'p1', 'p2', 'p3'],
};

const escape = (text) =>
  text
    .replace(/\s+/g, ' ')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\|/g, '&#124;')
    .replace(/[\\`*_[\]!~]/g, '\\$&');

const classify = (issue) => {
  if (
    !Number.isSafeInteger(issue.number) ||
    issue.number < 1 ||
    typeof issue.title !== 'string' ||
    !Array.isArray(issue.labels)
  )
    throw new Error('Invalid issue metadata');
  const labels = issue.labels.map((label) => (typeof label === 'string' ? label : label.name));
  const fields = {};
  const problems = [];
  for (const [kind, allowed] of Object.entries(groups)) {
    const values = labels
      .filter((label) => label.startsWith(`${kind}:`))
      .map((label) => label.slice(kind.length + 1))
      .sort();
    fields[kind] = values.length ? values.map(escape).join(', ') : '—';
    if (values.length === 0 && kind !== 'priority') problems.push(`missing ${kind}`);
    if (values.length > 1) problems.push(`multiple ${kind} labels: ${values.join(', ')}`);
    for (const value of values) {
      if (!allowed.includes(value)) problems.push(`unknown ${kind}:${value}`);
    }
    if (kind === 'status')
      fields.group =
        values.length === 1 && allowed.includes(values[0]) ? values[0] : 'unclassified';
  }
  return { ...issue, fields, problems };
};

/** Deterministic projection only. No interpretation of acceptance, PRs or comments. */
export const renderView = (input) => {
  const issues = input
    .filter((issue) => issue.state === 'open' && !issue.pull_request)
    .map(classify);
  issues.sort((a, b) => a.number - b.number);
  const lines = [
    VIEW_MARKER,
    '## Generated backlog',
    '',
    'Source: open issues and their labels. Edit the individual issues, not this view.',
    'Priorities belong to the owner. A merged PR does not automatically complete an issue.',
    'Details, evidence, blockers and PR links remain in each issue; decisions remain in #30 and the contracts/ADRs.',
    '',
    `**${issues.length} open issues.**`,
    '',
    '| Status | Count |',
    '| --- | ---: |',
  ];
  const order = [...groups.status, 'unclassified'];
  for (const status of order)
    lines.push(`| ${status} | ${issues.filter((issue) => issue.fields.group === status).length} |`);
  lines.push('', '| Milestone | Count |', '| --- | ---: |');
  for (const milestone of groups.milestone)
    lines.push(
      `| ${milestone} | ${issues.filter((issue) => issue.fields.milestone === milestone).length} |`,
    );
  lines.push(
    `| missing / conflicting / unknown | ${issues.filter((issue) => !groups.milestone.includes(issue.fields.milestone)).length} |`,
  );
  for (const status of order) {
    const selected = issues.filter((issue) => issue.fields.group === status);
    if (!selected.length) continue;
    lines.push(
      '',
      `### ${status}`,
      '',
      '| Issue | Area | Milestone | Priority |',
      '| --- | --- | --- | --- |',
    );
    for (const issue of selected) {
      lines.push(
        `| [#${issue.number} ${escape(issue.title)}](https://github.com/${REPOSITORY}/issues/${issue.number}) | ${issue.fields.area} | ${issue.fields.milestone} | ${issue.fields.priority} |`,
      );
    }
  }
  const anomalies = issues.filter((issue) => issue.problems.length);
  lines.push('', '### Classification anomalies', '');
  if (!anomalies.length) lines.push('None. Priority may be unspecified.');
  for (const issue of anomalies)
    lines.push(
      `- [#${issue.number}](https://github.com/${REPOSITORY}/issues/${issue.number}): ${issue.problems.map(escape).join('; ')}.`,
    );
  lines.push(
    '',
    'Generated by the repository Backlog view workflow. This is a projection, not another tracking source.',
  );
  return `${lines.join('\n')}\n`;
};

const paginate = async (api, path) => {
  const results = [];
  for (let page = 1; ; page++) {
    const separator = path.includes('?') ? '&' : '?';
    const items = await api('GET', `${path}${separator}per_page=${PAGE_SIZE}&page=${page}`);
    if (!Array.isArray(items)) throw new Error('Expected a GitHub list response');
    results.push(...items);
    if (items.length < PAGE_SIZE) return results;
  }
};

/** Writes only the single Actions-owned comment on #30. Never patches an issue body. */
export const syncView = async (
  api,
  { preview = false, now = () => new Date().toISOString() } = {},
) => {
  const root = `/repos/${REPOSITORY}/issues`;
  const issues = await paginate(api, `${root}?state=open`);
  const view = renderView(issues);
  if (preview) return { action: 'preview', view };
  const comments = await paginate(api, `${root}/${TARGET}/comments`);
  const candidates = comments.filter(
    (comment) =>
      comment.body?.startsWith(VIEW_MARKER) && comment.user?.login === 'github-actions[bot]',
  );
  if (candidates.length > 1)
    throw new Error(
      'Multiple Actions-owned backlog views; resolve the duplicate before publishing',
    );
  const digest = createHash('sha256').update(view).digest('hex');
  const fingerprint = `<!-- backlog-content-sha256:${digest} -->`;
  const existing = candidates[0];
  const previousContent = existing?.body.replace(/\nSnapshot updated \(UTC\): [^\n]+\n$/, '\n');
  if (previousContent === `${view}\n${fingerprint}\n`) {
    return { action: 'unchanged', url: existing.html_url, view };
  }
  const body = `${view}\n${fingerprint}\nSnapshot updated (UTC): ${now()}\n`;
  // GitHub comment limit; fail rather than silently omit issues or history.
  if (body.length > 60_000)
    throw new Error(
      'Backlog view exceeds the comment size budget; split the projection before publishing',
    );
  if (existing && !Number.isSafeInteger(existing.id))
    throw new Error('Invalid generated-comment ID');
  const result = existing
    ? await api('PATCH', `${root}/comments/${existing.id}`, { body })
    : await api('POST', `${root}/${TARGET}/comments`, { body });
  return { action: existing ? 'updated' : 'created', url: result.html_url, view };
};

export const githubApi = (token) => async (method, path, body) => {
  const response = await fetch(`https://api.github.com${path}`, {
    method,
    headers: {
      Accept: 'application/vnd.github+json',
      'X-GitHub-Api-Version': '2022-11-28',
      ...(token ? { Authorization: `Bearer ${token}` } : {}),
      ...(body ? { 'Content-Type': 'application/json' } : {}),
    },
    ...(body ? { body: JSON.stringify(body) } : {}),
    signal: AbortSignal.timeout(30_000),
  });
  if (!response.ok)
    throw new Error(
      `GitHub ${method} ${path} failed (${response.status}); no retry writes were attempted`,
    );
  return response.json();
};

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const arguments_ = process.argv.slice(2);
    if (arguments_.length !== 1 || !['--preview', '--publish'].includes(arguments_[0]))
      throw new Error('Usage: node scripts/backlog-view.mjs --preview|--publish');
    const preview = arguments_[0] === '--preview';
    if (process.env.GITHUB_REPOSITORY && process.env.GITHUB_REPOSITORY !== REPOSITORY)
      throw new Error('This workflow is scoped to Flourprint only');
    const token = process.env.GITHUB_TOKEN;
    if (!preview && (!token || process.env.GITHUB_ACTIONS !== 'true'))
      throw new Error('Publish only through the repository workflow and its GITHUB_TOKEN');
    const result = await syncView(githubApi(token), { preview });
    console.log(preview ? result.view : `${result.action}: ${result.url}`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
