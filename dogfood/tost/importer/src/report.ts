import { FIELDS } from './fields.js';
import type { RecipeReport } from './migrate.js';

const list = (title: string, items: readonly string[]) =>
  items.length === 0 ? [] : [`**${title}**`, '', ...items.map((i) => `- ${i}`), ''];

const grams = (value: number) => `${value} g`;

/** Human-readable migration report (Markdown). The JSON report carries the same data. */
export const reportMarkdown = (
  reports: readonly RecipeReport[],
  source: { file: string; sha256: string },
): string => {
  const count = (status: string) => reports.filter((r) => r.status === status).length;
  const lines = [
    '# TOST migration report',
    '',
    `Source: \`${source.file}\` (sha256 \`${source.sha256}\`), never modified.`,
    `Generated by \`dogfood/tost/importer\`; do not edit by hand.`,
    '',
    `${reports.length} recipes: ${count('converted')} converted, ${count('converted-with-warning')} converted with warnings, ${count('needs-review')} to review.`,
    '',
    '| Recipe | Status | Family | Anchor | TOST flour / water / dough | Flourprint flour / water / dough | Total water |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...reports.map((r) => {
      const t = r.comparison.tost;
      const f = r.comparison.flourprint;
      return `| ${r.name} (\`${r.legacyId}\`) | ${r.status} | ${r.family ?? '—'} | ${r.anchor} | ${t.mainFlour} / ${t.water} / ${t.dough} | ${f.flourTotal} / ${f.pureWater} / ${f.doughWeight} | ${f.totalWaterPct} %${f.totalWaterComplete ? '' : ' (incomplete)'} vs TOST ${t.hydrationPct} % |`;
    }),
    '',
    'TOST flour is the main flour (tangzhong flour excluded) and its water is what it had you weigh',
    'for the dough (tangzhong prepared on the side). Flourprint flour includes the tangzhong flour,',
    'its water includes the tangzhong and poolish water, and its dough includes salt and yeast.',
    '',
  ];
  for (const r of reports) {
    const t = r.comparison.tost;
    const f = r.comparison.flourprint;
    lines.push(
      `## ${r.name}`,
      '',
      `\`${r.legacyId}\` → \`${r.recipeId}\` · **${r.status}** · created ${r.createdAt}${r.family ? ` · family ${r.family}` : ''}`,
      '',
      `Anchor: ${r.anchor}.`,
      '',
      ...list('Flours', r.flours),
      '**Numbers (whole batch)**',
      '',
      '| | TOST | Flourprint |',
      '| --- | --- | --- |',
      `| Flour | ${grams(t.mainFlour)} main + tangzhong ${grams(t.tangzhong)} | ${grams(f.flourTotal)} total |`,
      `| Water | ${grams(t.water)} to weigh | ${grams(f.pureWater)} pure, ${grams(f.finalMixWater)} in the final mix |`,
      `| Salt / yeast | ${grams(t.salt)} / ${grams(t.yeast)} | same grams |`,
      ...Object.entries(t.extras).map(([id, g]) => `| ${id} | ${grams(g)} | same grams |`),
      `| Dough | ${grams(t.dough)} without salt and yeast | ${grams(f.doughWeight)} with them |`,
      `| Hydration | ${t.hydrationPct} % (TOST model) | pure ${f.pureWaterPct} %, total ${f.totalWaterPct} %${f.totalWaterComplete ? '' : ' (incomplete)'} |`,
      ...(f.totalFatPct === undefined
        ? []
        : [`| Fat / sugar | — | ${f.totalFatPct} % / ${f.totalSugarPct} % |`]),
      ...Object.entries(f.components).map(
        ([id, c]) => `| ${id} | | ${grams(c.flour)} flour, ${grams(c.water)} water |`,
      ),
      '',
      `TOST's stored dough differs from its own model by ${t.doughResidualPerPiece} g per piece (rounding).`,
      '',
      ...list('To review', r.reviews),
      ...list('Warnings', r.warnings),
      ...list('Engine', r.engine),
      ...list('Assumptions', r.assumptions),
      ...list('Not migrated', r.dropped),
    );
  }
  lines.push(
    '## Field inventory',
    '',
    '| Field | Class | Use |',
    '| --- | --- | --- |',
    ...Object.entries(FIELDS)
      .sort(([a], [b]) => (a < b ? -1 : 1))
      .map(([name, [kind, use]]) => `| \`${name}\` | ${kind} | ${use} |`),
    '',
  );
  return lines.join('\n');
};
